import re
from dataclasses import dataclass

EXCLUDED = {"Cc", "Cf", "Cs", "Co", "Cn", "Zs", "Zl", "Zp", "Mn", "Mc", "Me"}
GENERAL = (0x2000, 0x2BFF)
ARROW_SPACES = (GENERAL, (0x1F800, 0x1F8FF))


@dataclass(frozen=True)
class Rule:
    id: str
    ranges: tuple = ()
    pattern: object = None
    pattern_in: tuple = ()
    categories: frozenset = frozenset()
    letters: bool = False


def word(*names):
    return re.compile(r"\b(" + "|".join(names) + r")\b")


