CATEGORY_IDS = tuple(rule.id for rule in RULES)


def in_ranges(cp, ranges):
    return any(low <= cp <= high for low, high in ranges)


def matches(rule, cp, character):
    if character.category in rule.categories:
        return True
    if in_ranges(cp, rule.ranges):
        return True
    return rule.pattern is not None and in_ranges(cp, rule.pattern_in) and bool(rule.pattern.search(character.name))


def classify(cp, character):
    if character.category in EXCLUDED:
        return None
    for rule in RULES:
        if character.category.startswith("L") and not rule.letters:
            continue
        if matches(rule, cp, character):
            return rule.id
    return None
